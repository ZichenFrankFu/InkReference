"""Shared character business contract for catalog, text analysis and web drafts.

    Stable identities are shared; source proof is an optional internal layer for
    human/web records and mandatory for extraction provider output.
"""
from __future__ import annotations

import copy
from typing import Any

TEMPERAMENTS = ("强大", "智谋", "利他", "共情", "利己", "执念", "反差", "宿命")


def obj(properties, required=None):
    return {"type": "object", "additionalProperties": False, "properties": properties,
            "required": list(properties if required is None else required)}


def txt(size=10000, empty=True):
    return {"type": "string", "minLength": 0 if empty else 1, "maxLength": size}


def arr(item):
    return {"type": "array", "items": item, "maxItems": 10000}


ID = txt(160, False)
PROGRESS = {"type": "number", "minimum": 0, "maximum": 100}
STORY_TIME = {"type": ["string", "null"], "maxLength": 1000}
RANGE = obj({"start": PROGRESS, "end": {"type": ["number", "null"], "minimum": 0, "maximum": 100}})
RELATIONSHIP = obj({"character_id": ID, "relationship": txt()})
RELATIONSHIPS = arr(RELATIONSHIP)
PROVENANCE = {"revealed_at": obj({"chapter": {"type": ["integer", "null"], "minimum": 1},
                                   "offset": {"type": ["integer", "null"], "minimum": 0}}),
              "source_version_id": txt(160), "evidence": txt(10000, False),
              "origin": {"type": "string", "enum": ["source", "manual"]}}
INITIAL = obj({"gender": {"type": ["string", "null"], "enum": [None, "男", "女", "特殊"]}, "age": txt(200),
               "identity": txt(), "ability": txt(), "personality": txt(), "appearance": txt(),
               "relationships": RELATIONSHIPS, "narrative_progress": PROGRESS, "story_time": STORY_TIME})
SNAPSHOT_FIELDS = {"id": ID, "narrative_range": RANGE, "story_time": STORY_TIME, "event_ids": arr(ID),
                   "identity": txt(), "ability": txt(), "personality": txt(), "appearance": txt(),
                   "visual_design": txt(), "relationships": RELATIONSHIPS}
SNAPSHOT = obj({**SNAPSHOT_FIELDS, **PROVENANCE}, SNAPSHOT_FIELDS)
CHARACTER_FIELDS = {"schema_version": {"type": "integer", "enum": [3]}, "id": ID, "name": txt(1000, False),
                    "aliases": arr(txt(1000, False)), "role_tag": txt(200),
                    "temperament": {"type": "string", "enum": ["", *TEMPERAMENTS]}, "visual_design": txt(),
                    "initial_state": INITIAL, "snapshots": arr(SNAPSHOT)}
CHARACTER_SCHEMA = obj({**CHARACTER_FIELDS, **PROVENANCE}, CHARACTER_FIELDS)


def normalize_character(value: Any, *, require_provenance: bool = False) -> dict:
    if not isinstance(value, dict):
        from .database import DataError
        raise DataError(422, "角色需为对象")
    if value.get("schema_version") == 4:
        from .analysis_contract_v4 import normalize_v4_section
        return validate_character(normalize_v4_section("characters", [value], manual=not require_provenance)[0], require_provenance=require_provenance)
    if value.get("schema_version") != 3:
        from .chronicle_schema import adapt_v2_section
        result = adapt_v2_section("characters", [value])[0]
    else:
        result = copy.deepcopy(value)
    # Omitted business strings are empty, not invented facts. Identity and names
    # still require explicit values; they must never be generated by title match.
    result.setdefault("aliases", [])
    for key in ("role_tag", "temperament", "visual_design"): result.setdefault(key, "")
    initial = result.setdefault("initial_state", {})
    initial.setdefault("gender", None)
    for key in ("age", "identity", "ability", "personality", "appearance"): initial.setdefault(key, "")
    initial.setdefault("relationships", [])
    initial.setdefault("narrative_progress", 0)
    initial.setdefault("story_time", None)
    result.setdefault("snapshots", [])
    for snapshot in result["snapshots"]:
        if not isinstance(snapshot, dict): continue
        for key in ("identity", "ability", "personality", "appearance", "visual_design"): snapshot.setdefault(key, "")
        snapshot.setdefault("relationships", [])
        snapshot.setdefault("event_ids", [])
        snapshot.setdefault("story_time", None)
    if not require_provenance:
        for fact in [result, *result["snapshots"]]:
            if not fact.get("evidence"):
                for key in ("evidence", "revealed_at", "source_version_id"): fact.pop(key, None)
                fact["origin"] = "manual"
    return validate_character(result, require_provenance=require_provenance)


def validate_character(value: Any, *, require_provenance: bool = False) -> dict:
    from .chronicle_schema import _validate, require_source_schema
    base_schema = CHARACTER_V4_SCHEMA if isinstance(value, dict) and value.get("schema_version") == 4 else CHARACTER_SCHEMA
    schema = require_source_schema(base_schema) if require_provenance else base_schema
    _validate(value, schema, "characters")
    for snapshot in value["snapshots"]:
        span = snapshot["narrative_range"]
        if span["end"] is not None and span["end"] < span["start"]:
            from .database import DataError
            raise DataError(422, "阶段叙事进度的结束不能早于开始")
    return copy.deepcopy(value)


# Keep the v3 schema immutable for old runs and cache snapshots.
CHARACTER_V4_SCHEMA = copy.deepcopy(CHARACTER_SCHEMA)
CHARACTER_V4_SCHEMA["properties"]["schema_version"]["enum"] = [4]
CHARACTER_V4_SCHEMA["properties"]["snapshots"]["items"]["properties"]["name"] = txt(1000)
CHARACTER_V4_SCHEMA["properties"]["snapshots"]["items"]["required"].append("name")
