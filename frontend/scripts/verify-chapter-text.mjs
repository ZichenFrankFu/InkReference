import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import ts from "typescript";
const source = await readFile(fileURLToPath(new URL("../src/chapterText.ts", import.meta.url)), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { textareaText, preserveTextareaEdit } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const raw = "🌟第一行\r\n第二行\r\n第三行\r\n";
assert.equal(preserveTextareaEdit(raw, textareaText(raw).value), raw);
assert.equal(preserveTextareaEdit(raw, "🌟第一行\n第二行修订\n第三行\n"), "🌟第一行\r\n第二行修订\r\n第三行\r\n");
assert.equal(preserveTextareaEdit(raw, "🌟第一行\n新增段\n第二行\n第三行\n"), "🌟第一行\r\n新增段\r\n第二行\r\n第三行\r\n");
assert.equal(preserveTextareaEdit("前\r\n中\n后\r尾", "前\n中改\n后\n尾"), "前\r\n中改\n后\r尾");
assert.equal(preserveTextareaEdit("甲\r乙\r", "甲\n中文\n乙\n"), "甲\r中文\r乙\r");
assert.equal(preserveTextareaEdit("🌟甲\r\n乙", "🌙甲\n乙"), "🌙甲\r\n乙");
const model = textareaText("🌟甲\r\n乙");
assert.equal(model.value, "🌟甲\n乙");
assert.equal(model.sourceToDisplay[4], 3);
assert.equal(Array.from(model.value).slice(0, model.sourceToDisplay[4]).join("").length, 4);
assert.deepEqual(model.rawBoundaries, [0, 1, 2, 3, 5, 6]);
console.log("10 chapter text preservation and Unicode offset checks passed");
